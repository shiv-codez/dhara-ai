/**
 * HTML entity escaping utility to prevent XSS in Leaflet tooltips,
 * divIcons, and any dynamic HTML strings.
 */
export function escapeHtml(str) {
  if (str == null) return ''
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;')
}
